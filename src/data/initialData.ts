// Helper to generate sample timestamps for recent days
const now = new Date();
const getSampleDate = (daysAgo: number, hours = 10, minutes = 0) => {
  const d = new Date(now);
  d.setDate(d.getDate() - daysAgo);
  d.setHours(hours, minutes, 0, 0);
  return d.toISOString();
};

